// QA-only dependencies are supplied externally; no production package change.
const { spawn } = require('node:child_process')
const assert = require('node:assert/strict')
const { chromium } = require(process.env.QA_PLAYWRIGHT_MODULE || 'playwright')
const server = spawn(process.execPath,['node_modules/next/dist/bin/next','start','--hostname','127.0.0.1','--port','3110'],{stdio:'ignore'})
;(async()=>{
 let browser
 try {
  for(let i=0;i<30;i++){try {const res=await fetch('http://127.0.0.1:3110/');if(res.ok)break}catch{};await new Promise(r=>setTimeout(r,300))}
  browser=await chromium.launch({executablePath:process.env.QA_CHROMIUM_PATH,headless:true,args:['--no-sandbox','--disable-dev-shm-usage','--disable-gpu']})
  const page=await browser.newPage({viewport:{width:1440,height:1000}})
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto('http://127.0.0.1:3110/',{waitUntil:'networkidle'})
  assert.equal(await page.locator('.guide-card').count(),4)
  await page.getByRole('button',{name:'스마트폰',exact:true}).click()
  assert.equal(await page.locator('.guide-card').count(),2)
  await page.getByRole('searchbox',{name:'가이드 검색'}).fill('액체')
  assert.equal(await page.locator('.guide-card').count(),1)
  await page.getByRole('searchbox',{name:'가이드 검색'}).fill('없는검색어')
  assert.equal(await page.locator('.guide-card').count(),0)
  await page.getByRole('searchbox',{name:'가이드 검색'}).fill('')
  await page.getByRole('button',{name:'전체',exact:true}).click()
  await page.getByLabel('수리·단품 구매 총비용 (원)').fill('80000')
  await page.getByLabel('새 제품 결제금액 (원)').fill('150000')
  await page.getByLabel('새 제품 추가 비용 (원)').fill('3000')
  assert.ok((await page.locator('.cost-result').innerText()).includes('73,000원'))
  await page.getByLabel('수리·단품 구매 총비용 (원)').fill('200000')
  assert.ok((await page.locator('.cost-result').innerText()).includes('47,000원'))
  for(const label of ['수리·단품 구매 총비용 (원)','새 제품 결제금액 (원)','새 제품 추가 비용 (원)'])await page.getByLabel(label).fill('')
  await page.evaluate(async()=>{document.activeElement?.blur();scrollTo(0,0);await document.fonts.ready})
  assert.ok(await page.evaluate(()=>document.fonts.check('16px Pretendard','한글')))
  await page.screenshot({path:'docs/previews/home-v2-desktop.png',fullPage:true})
  for(const width of [375,320]){
   await page.setViewportSize({width,height:850})
   await page.evaluate(()=>scrollTo(0,0))
   assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`Overflow at ${width}px`)
   await page.screenshot({path:`docs/previews/home-v2-mobile-${width}.png`,fullPage:true})
  }
  await page.goto('http://127.0.0.1:3110/search?q='+encodeURIComponent('액체'),{waitUntil:'networkidle'})
  assert.equal(await page.locator('a[href="/hub/iphone-17-pro/liquid-detected-before-buying-cable"]').count(),1)
  await page.goto('http://127.0.0.1:3110/hub/galaxy-buds4/single-bud-replacement',{waitUntil:'networkidle'})
  assert.equal(await page.locator('a[href="/go/buds4-body"]').count(),1)
  assert.equal(await page.locator('a[href="https://www.samsungsvc.co.kr/solution/25084"]').count(),1)
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Article overflow at 320px')
  await page.screenshot({path:'docs/previews/guide-v2-mobile.png',fullPage:true})
  assert.deepEqual(errors,[])
  console.log('PASS: real-browser filters, search, both cost comparisons, 320/375px overflow, source links, no JS errors')
 }finally{if(browser)await browser.close();server.kill()}
})().catch(e=>{console.error(e);process.exitCode=1})
